function normalizeLanguage(value) {
  return value === 'ar' ? 'ar' : 'fr'
}

function normalizePhrase(value) {
  return value
    .replace(/\s+/g, ' ')
    .replace(/\s+([:؟?!%])/g, '$1')
    .trim()
}

function translateText(value, language) {
  if (!value || !value.trim()) return value
  let next = value
  const leading = value.match(/^\s*/)?.[0] || ''
  const trailing = value.match(/\s*$/)?.[0] || ''
  const core = normalizePhrase(value)
  const map = language === 'ar' ? domArabicMap : domFrenchMap
  const translated = map.get(core)
  if (translated) next = `${leading}${translated}${trailing}`
  if (language === 'ar') {
    next = next.replace(/\bMAD\b/g, 'درهم')
    next = next.replace(/^Total \((\d+)\)$/u, 'المجموع ($1)')
    next = next.replace(/^Stock:\s*/u, 'المخزون: ')
    next = next.replace(/^Maj:\s*/u, 'تحديث: ')
    next = next.replace(/^Min:\s*/u, 'الحد الأدنى: ')
    next = next.replace(/^Qte:\s*/u, 'الكمية: ')
    next = next.replace(/^Qté:\s*/u, 'الكمية: ')
    next = next.replace(/^(\d+)-(\d+) \/ (\d+) produits$/u, '$1-$2 / $3 منتجات')
    next = next.replace(/^(\d+) ligne\(s\)$/u, '$1 سطر')
    next = next.replace(/^(\d+) permissions$/u, '$1 صلاحية')
    next = next.replace(/ produit\(s\) en stock faible:/u, ' منتج في مخزون منخفض:')
    next = next.replace(/^Stock disponible:/u, 'المخزون المتاح:')
    next = next.replace(/^Ticket /u, 'تذكرة ')
    next = next.replace(/^Payé:/u, 'المؤدى:')
    next = next.replace(/^Paye:/u, 'المؤدى:')
    next = next.replace(/^Reste:/u, 'الباقي:')
    next = next.replace(/^Sous-total HT$/u, 'المجموع بدون TVA')
    next = next.replace(/^Total TTC$/u, 'المجموع مع TVA')
    next = next.replace(/^Remise globale$/u, 'خصم عام')
    next = next.replace(/^TVA$/u, 'TVA')
    next = next.replace(/—/g, '-')
  } else {
    next = next.replace(/درهم/g, 'MAD')
  }
  return next
}

function localizeDom(language) {
  const root = document.getElementById('root')
  if (!root) return
  const ignored = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT'])
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement
      if (!parent || ignored.has(parent.tagName)) return NodeFilter.FILTER_REJECT
      if (!node.nodeValue?.trim()) return NodeFilter.FILTER_REJECT
      return NodeFilter.FILTER_ACCEPT
    },
  })
  const textNodes = []
  while (walker.nextNode()) textNodes.push(walker.currentNode)
  textNodes.forEach(node => {
    const next = translateText(node.nodeValue, language)
    if (next !== node.nodeValue) node.nodeValue = next
  })
  root.querySelectorAll('[placeholder], [title], [aria-label]').forEach(el => {
    for (const attr of ['placeholder', 'title', 'aria-label']) {
      const value = el.getAttribute(attr)
      if (!value) continue
      const next = translateText(value, language)
      if (next !== value) el.setAttribute(attr, next)
    }
  })
}

function readInitialLanguage() {
  try {
    return normalizeLanguage(localStorage.getItem(STORAGE_KEY) || 'fr')
  } catch {
    return 'fr'
  }
}

const I18nCtx = createContext(null)

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(readInitialLanguage)

  const setLanguage = (nextLanguage) => {
    const normalized = normalizeLanguage(nextLanguage)
    setLanguageState(normalized)
    localStorage.setItem(STORAGE_KEY, normalized)
    window.dispatchEvent(new CustomEvent('proerp:language-change', { detail: normalized }))
  }

  useEffect(() => {
    const meta = LANGUAGES[language]
    document.documentElement.lang = language
    document.documentElement.dir = meta.dir
    document.body.dataset.lang = language
    document.body.classList.toggle('rtl', meta.dir === 'rtl')
  }, [language])

  useEffect(() => {
    let frame = 0
    const run = () => {
      cancelAnimationFrame(frame)
      frame = requestAnimationFrame(() => localizeDom(language))
    }
    run()
    const root = document.getElementById('root')
    if (!root) return () => cancelAnimationFrame(frame)
    const observer = new MutationObserver(run)
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] })
    return () => {
      cancelAnimationFrame(frame)
      observer.disconnect()
    }
  }, [language])

  useEffect(() => {
    const onStorage = (event) => {
      if (event.key === STORAGE_KEY) setLanguageState(normalizeLanguage(event.newValue))
    }
    const onLocalChange = (event) => setLanguageState(normalizeLanguage(event.detail))
    window.addEventListener('storage', onStorage)
    window.addEventListener('proerp:language-change', onLocalChange)
    return () => {
      window.removeEventListener('storage', onStorage)
      window.removeEventListener('proerp:language-change', onLocalChange)
    }
  }, [])

  const value = useMemo(() => {
    const t = (key) => messages[language]?.[key] || messages.fr[key] || key
    const locale = LANGUAGES[language].locale
    const dir = LANGUAGES[language].dir
    const formatNumber = (n, decimals = 2) => Number(n || 0).toLocaleString(locale, {
      minimumFractionDigits: decimals,
      maximumFractionDigits: decimals,
    })
    const formatMoney = (n, decimals = 2) => {
      const amount = formatNumber(n, decimals)
      return language === 'ar' ? `${amount} درهم` : `${amount} DH`
    }
    return { language, setLanguage, t, dir, locale, isRtl: dir === 'rtl', formatNumber, formatMoney }
  }, [language])

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nCtx)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
